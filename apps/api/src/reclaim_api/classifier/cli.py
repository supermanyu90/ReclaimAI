"""reclaim-classifier train | predict | vertex-train [--submit] | vertex-batch [--submit]

train   trains locally (reproducible), saves the artifact under MODELS_DIR and writes
        docs/model_card.md from the measured, synthetic-only results.
predict local batch prediction: features from the warehouse → predictions in the warehouse.
vertex-*  print the Vertex AI job spec; submit only with --submit (paid resources).
"""

import argparse
from dataclasses import asdict
from pathlib import Path

from reclaim_api.classifier import model, vertex


def models_dir() -> Path:
    from reclaim_api.config import get_settings
    from reclaim_api.seed import default_fixture_path

    s = get_settings()
    return Path(s.models_dir) if s.models_dir else default_fixture_path().parents[1] / ".data" / "models"


def model_card(report: model.Report) -> str:
    t = report.test
    rows = "\n".join(
        f"| {c} | {v['precision']:.3f} | {v['recall']:.3f} | {v['support']} |" for c, v in t["all_predictions"]["per_class"].items()
    )
    cm = t["all_predictions"]["confusion_matrix"]
    header = "| true \\ predicted | " + " | ".join(cm["labels"]) + " |"
    matrix = "\n".join(f"| {lab} | " + " | ".join(str(x) for x in row) + " |" for lab, row in zip(cm["labels"], cm["rows_true_cols_predicted"], strict=True))
    return f"""# Transaction category model card

**{report.model_version}**. Every number below was measured on **synthetic data** generated by
`classifier/data.py`. None of it says anything about real bank transactions, and the model
does not detect fraud. Regenerate with `reclaim-classifier train` (deterministic).

## Data and splits
- {report.data['rows']} synthetic transactions, {report.data['accounts']} accounts, seed {report.data['seed']}.
- Split by account; accounts sharing an identical narrative are kept together.
  Rows train/validation/test: {report.data['split_rows']}; accounts: {report.data['split_accounts']}.
- Narratives appearing in more than one split: {report.data['cross_split_duplicate_narratives']}.
- Deliberate ambiguity: bare NACH mandate debits (SIP vs EMI vs premium, same dates and
  overlapping amounts), plain IMPS credits (rent vs transfer), shop UPI handles that look like people.

## Model
TF-IDF character 2–4-grams on the digit-normalized narrative, direction, log amount, round amount
and day of month → class-balanced logistic regression (C={report.params['C']}).

## Abstention
Threshold chosen on validation only: the lowest confidence at which validation accuracy of the
kept predictions reaches {report.params['target_selective_precision']}. Chosen threshold: **{report.threshold}**
(validation coverage {report.validation['coverage']}, accuracy {report.validation['selective_accuracy']}).
Below it, a transaction goes to the owner's review queue.

## Held-out test results (synthetic)
- All predictions: macro-F1 **{t['all_predictions']['macro_f1']}**, accuracy {t['all_predictions']['accuracy']} (n={t['all_predictions']['n']}).
- With abstention: coverage {t['with_abstention']['coverage']}, {t['with_abstention']['abstained']} abstained,
  accuracy of kept predictions {t['with_abstention']['selective_accuracy']}; macro-F1 on kept {t['accepted_only']['macro_f1']}.
- Rules-only baseline (the fallback): coverage {report.test_rules_baseline['coverage']}, accuracy when matched {report.test_rules_baseline['accuracy_when_matched']}.

| class | precision | recall | support |
|---|---|---|---|
{rows}

Confusion matrix (all predictions):

{header}
|{'---|' * (len(cm['labels']) + 1)}
{matrix}

## Known limits
- Accounts whose mandates all read "NACH DR UMRN…" are confused *consistently and confidently*;
  abstention does not catch that, because the model is sure. Owner confirmation does.
- Kept-prediction accuracy on test was {t['with_abstention']['selective_accuracy']} against a validation target of
  {report.params['target_selective_precision']}: the target was {"met" if (t['with_abstention']['selective_accuracy'] or 0) >= report.params['target_selective_precision'] else "**not met**"} on held-out data.
  A threshold tuned on one sample does not guarantee the same accuracy on another.
- Agreement on the demo feed (`analytics/synthetic.py`) is not an evaluation: the feed and the
  training generator were written by the same author. An early version of the generator lacked
  common forms ("… TRANSFER", "HOME LOAN"); the demo feed exposed this (12 family transfers
  predicted as SIPs at 0.54 confidence) and the generator was broadened, not fitted to the feed.
- Predictions are suggestions. Confirmed categories are stored separately and only by the owner.
"""


def predict_all() -> tuple[int, int, str]:
    """Batch prediction: warehouse features → warehouse predictions. Returns (written, abstained, source)."""
    from reclaim_api.providers.registry import get_providers

    providers = get_providers()
    rows = providers.warehouse.query("features", {})
    preds = providers.classification.classify(rows)
    written = providers.warehouse.write_predictions([
        {"transaction_id": r["transaction_id"], "tenant_key": r["tenant_key"], "model_version": p.model_version, "source": p.source,
         "predicted_category": p.category, "confidence": p.confidence, "abstained": p.abstained}
        for r, p in zip(rows, preds, strict=True)
    ])  # fmt: skip
    return written, sum(p.abstained for p in preds), preds[0].source if preds else "-"


def main() -> None:
    parser = argparse.ArgumentParser(description="Transaction category classifier")
    parser.add_argument("command", choices=["train", "predict", "vertex-train", "vertex-batch"])
    parser.add_argument("--submit", action="store_true", help="actually submit the Vertex AI job (billed)")
    args = parser.parse_args()

    if args.command == "train":
        pipe, report = model.train()
        out = model.save(pipe, report, models_dir())
        from reclaim_api.seed import default_fixture_path

        card = default_fixture_path().parents[1] / "docs" / "model_card.md"
        card.write_text(model_card(report))
        t = report.test
        print(f"trained {report.model_version} → {out}")
        print(f"synthetic test: macro-F1 {t['all_predictions']['macro_f1']}, threshold {report.threshold}, "
              f"coverage {t['with_abstention']['coverage']}, kept accuracy {t['with_abstention']['selective_accuracy']}")  # fmt: skip
    elif args.command == "predict":
        written, abstained, source = predict_all()
        print(f"predicted {written} transactions; abstained {abstained}; source {source}")
    else:
        from reclaim_api.config import get_settings

        s = get_settings()
        spec = (vertex.training_spec(bucket=s.models_bucket or "<MODELS_BUCKET>", version_tag="latest") if args.command == "vertex-train"
                else vertex.batch_spec(bucket=s.models_bucket or "<MODELS_BUCKET>", model_uri=f"gs://{s.models_bucket}/models/txn-clf/latest/LATEST",
                                       dataset=f"{s.gcp_project}.{s.bigquery_dataset}"))  # fmt: skip
        if not args.submit:
            print("dry run (nothing submitted):")
            for key, value in asdict(spec).items():
                print(f"  {key}: {value}")
            return
        result = vertex.submit(spec, project=s.gcp_project, region=s.vertex_location, bucket=s.models_bucket)
        for key, value in result.items():
            print(f"{key}: {value}")
